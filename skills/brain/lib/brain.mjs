// Read-side operations over a store: list/load pages, rebuild the index, and
// lint `[[wiki-link]]` references. Every function takes an explicit storeDir so
// the CLI resolves the project identity exactly once.

import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { basename } from "node:path";
import {
  ROOT_PAGE_SLUGS,
  countDecisions,
  countTimeline,
  extractTruth,
  parseFrontmatter,
  splitFrontmatter,
  writeFileAtomic,
} from "./doc.mjs";
import { indexPath, pagesDir, rootPath } from "./store.mjs";

export function loadDoc(path) {
  const raw = readFileSync(path, "utf8");
  const { frontmatter, body } = splitFrontmatter(raw);
  return {
    id: basename(path, ".md"),
    path,
    raw,
    frontmatter: parseFrontmatter(frontmatter),
    rawFrontmatter: frontmatter,
    body,
  };
}

export function listPages(storeDir) {
  const dir = pagesDir(storeDir);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => loadDoc(`${dir}/${f}`));
}

export function listRootPages(storeDir) {
  if (!existsSync(storeDir)) return [];
  return ROOT_PAGE_SLUGS.map((slug) => rootPath(storeDir, slug))
    .filter((p) => existsSync(p) && statSync(p).isFile())
    .map((p) => loadDoc(p));
}

/** Strip fenced code blocks and inline code so their contents aren't scanned. */
export function stripCode(text) {
  return text.replace(/```[\s\S]*?```/g, "").replace(/`+[^`\n]*`+/g, "");
}

/** Every [[wiki-link]] target in a string, ignoring code spans/blocks. */
export function findWikiLinks(text) {
  const out = [];
  const re = /\[\[([^\]|]+?)\]\]/g;
  const scannable = stripCode(text);
  let m;
  while ((m = re.exec(scannable)) !== null) out.push(m[1].trim());
  return out;
}

/** Rebuild index.md from pages/. Returns { path, count }. */
export function reindex(storeDir) {
  const pages = listPages(storeDir).map((doc) => {
    const fm = doc.frontmatter;
    const id = fm.id || doc.id;
    const title = fm.title || "(untitled)";
    const category = fm.category || "?";
    const status = fm.status || "?";
    const tags = Array.isArray(fm.tags) ? fm.tags.join(", ") : fm.tags || "";
    const truth = extractTruth(doc.body);
    const summary = firstSentence(truth) || title;
    const meta = [
      `category: ${category}`,
      `status: ${status}`,
      `entries: ${countTimeline(doc.body)}`,
      `decisions: ${countDecisions(doc.body)}`,
    ];
    if (tags) meta.push(`tags: [${tags}]`);
    return `- [${id}](pages/${id}.md) — ${meta.join(" | ")} | ${summary}`;
  });

  const lines = [
    "# Brain Index",
    "",
    `_Auto-generated by \`brain reindex\`. Last updated ${new Date().toISOString()}._`,
    "",
    pages.length ? pages.join("\n") : "_(no pages yet)_",
    "",
  ];

  const path = indexPath(storeDir);
  writeFileAtomic(path, lines.join("\n"));
  return { path, count: pages.length };
}

function firstSentence(text) {
  if (!text) return "";
  const trimmed = text.trim();
  if (!trimmed) return "";
  const limit = Math.min(trimmed.length, 140);
  let end = limit;
  for (let i = 0; i < limit; i += 1) {
    const ch = trimmed[i];
    if (ch === "\n" || ch === "。") {
      end = i + 1;
      break;
    }
    if (ch === "." && !isWordChar(trimmed[i - 1]) && !isWordChar(trimmed[i + 1])) {
      end = i + 1;
      break;
    }
  }
  return trimmed.slice(0, end).replace(/\n/g, " ").trim();
}

function isWordChar(ch) {
  return typeof ch === "string" && /[A-Za-z0-9_-]/.test(ch);
}

/**
 * Verify every `[[page-id]]` resolves. Page compiled_truth and root page bodies
 * are current knowledge and are linted; timeline entries are append-only
 * provenance and are not.
 */
export function lintLinks(storeDir) {
  const pages = listPages(storeDir);
  const rootPages = listRootPages(storeDir);
  const pageIds = new Set(pages.map((p) => p.frontmatter.id || p.id));
  const rootSlugs = new Set(ROOT_PAGE_SLUGS);

  const broken = [];
  const rootRefs = [];
  const check = (from, text) => {
    for (const target of findWikiLinks(text)) {
      if (pageIds.has(target)) continue;
      if (rootSlugs.has(target)) rootRefs.push({ from, target });
      else broken.push({ from, target });
    }
  };

  for (const doc of pages) check(doc.path, extractTruth(doc.body) || "");
  for (const doc of rootPages) check(doc.path, doc.body);

  return { broken, rootRefs, pageCount: pages.length, rootCount: rootPages.length };
}
